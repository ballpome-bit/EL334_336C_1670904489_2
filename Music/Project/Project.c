static void processInterruptEvents(void) {               /* ?????????????????????????????????????????????? */
    if (flagS2Pressed) {                                 /* ?????????????? S2 */
        flagS2Pressed = false;                           /* ????????????? S2 */
        if (currentState == STATE_IDLE_HELLO) {          /* ??????????? HELLO */
            currentState = STATE_SELECT_SONG;            /* ??????????????????????????? */
        } else if (currentState == STATE_SELECT_SONG) {  /* ???????????????????? */
            currentState = STATE_PLAYING_SONG;           /* ???????????????????????????????? */
            playSelectedSongWithControls(selectedSongIndex); /* ???????????????????????? */
            currentState = STATE_SELECT_SONG;            /* ????????????????? Cancel ?????????????????????? */
        }
    }
    if (flagS3Pressed) {                                 /* ?????????????? S3 */
        flagS3Pressed = false;                           /* ????????????? S3 */
        if (currentState == STATE_SELECT_SONG) {         /* ???????????????????? */
            selectedSongIndex++;                         /* ????????????????? (+1) */
            if (selectedSongIndex > TOTAL_SONGS) selectedSongIndex = 1; /* ?????????????????? ?????????????????? 1 */
        }
    }
    if (flagS1Pressed) {                                 /* ?????????????? S1 */
        flagS1Pressed = false;                           /* ????????????? S1 */
        if (currentState == STATE_SELECT_SONG) {         /* ???????????????????? */
            selectedSongIndex--;                         /* ???????????????????????? (-1) */
            if (selectedSongIndex < 1) selectedSongIndex = TOTAL_SONGS; /* ??????????? 1 ?????????????????? (5) */
        }
    }
}

