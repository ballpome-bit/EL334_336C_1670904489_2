static void shiftOutByte(uint8_t byteVal) {              /* ????????????????? 1 ???? (8 ???) ???? 74HC595 ??????? */
    int i;                                               /* ???????????? */
    for (i = 7; i >= 0; i--) {                           /* ???????????????????? (MSB: ??? 7) ??????????? (LSB: ??? 0) */
        if ((byteVal >> i) & 0x01) DATA_HIGH();          /* ?????????????? 1 ?????? Data High */
        else DATA_LOW();                                 /* ?????????????? 0 ?????? Data Low */
        delay_short();                                   /* ?????????????????? Data ???? */
        CLOCK_HIGH();                                    /* ????????????????? Clock ?????????????????? */
        delay_short();                                   /* ????????? */
        CLOCK_LOW();                                     /* ??? Clock ?????? Low ?????????????????????? */
        delay_short();                                   /* ????????? */
    }
}

static void writeDigitToShield(uint8_t digitBitmask, uint8_t segmentPattern) { /* ??????????????? 1 ???????? Shield */
    LATCH_LOW();                                         /* ??? Latch ?? Low ?????????????????????????? */
    delay_short();                                       /* ????????? */
    shiftOutByte(segmentPattern);                        /* ?????????? 1: ????????????????? (Segment A-G, DP) */
    shiftOutByte(digitBitmask);                          /* ?????????? 2: ?????????????????????? (Digit 1-4) */
    LATCH_HIGH();                                        /* ??? Latch ???? High ??????????????????????????????? */
    delay_short();                                       /* ????????? */
}

static void renderDisplayBuffer(uint8_t displayBuffer[4], int duration_ms) { /* ?????????????????????? 4 ???? (Multiplexing) */
    const uint8_t DIGIT_SELECT[4] = { 0x01, 0x02, 0x04, 0x08 }; /* ?????????????????????????????? (???? 1 ??? 4) */
    uint32_t start_ms = g_sysTickMs;                     /* ????????????????????? */
    int i;                                               /* ????????????? */

    while ((g_sysTickMs - start_ms) < (uint32_t)duration_ms) { /* ??????????????????????????? duration_ms */
        for (i = 0; i < 4; i++) {                        /* ???????????????????????? 0 ??? 3 */
            writeDigitToShield(DIGIT_SELECT[i], displayBuffer[i]); /* ????????????????????? i */
            delay_ms(2);                                 /* ??????????? 2 ms ???????????????????? */
            writeDigitToShield(0x00, SEG_BLANK);         /* ?????????????????????????????????? (??????????/???) */
        }
    }
}

